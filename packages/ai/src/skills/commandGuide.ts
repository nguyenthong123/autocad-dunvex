/**
 * Searches for a command guide card by exact commandKey, alias, or Vietnamese/English keyword.
 */
export function findCommandGuide(query: string): CommandGuideCard | undefined {
    if (!query) return undefined;
    const q = query.trim().toLowerCase();

    // 1. Exact match on commandKey
    const exact = COMMAND_GUIDE_CARDS.find((c) => c.commandKey.toLowerCase() === q);
    if (exact) return exact;

    // 2. Exact match on aliases
    const aliasMatch = COMMAND_GUIDE_CARDS.find((c) => c.aliases.some((a) => a.toLowerCase() === q));
    if (aliasMatch) return aliasMatch;

    // 3. Substring match on commandKey, aliases, or purpose
    return COMMAND_GUIDE_CARDS.find(
        (c) =>
            c.commandKey.toLowerCase().includes(q) ||
            c.aliases.some((a) => a.toLowerCase().includes(q)) ||
            c.purpose.toLowerCase().includes(q),
    );
}

/**
 * Searches and returns all matching command guide cards.
 */
export function searchCommandGuides(query: string): CommandGuideCard[] {
    if (!query?.trim()) return [...COMMAND_GUIDE_CARDS];
    const q = query.trim().toLowerCase();
    return COMMAND_GUIDE_CARDS.filter(
        (c) =>
            c.commandKey.toLowerCase().includes(q) ||
            c.aliases.some((a) => a.toLowerCase().includes(q)) ||
            c.category.toLowerCase().includes(q) ||
            c.purpose.toLowerCase().includes(q) ||
            c.geometryConstraints.some((g) => g.toLowerCase().includes(q)),
    );
}

